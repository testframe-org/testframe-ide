const dictionaries: Record<Lang, Record<TKey, string>> = { en, 'pt-BR': pt };

export interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

const STORAGE_KEY = 'testframe.lang';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>('en');

  // The stored language is read after mount so the server render and the first client render agree.
  useEffect(() => {
    if (window.localStorage.getItem(STORAGE_KEY) === 'pt-BR') setLang('pt-BR');
  }, []);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';
  }, [lang]);

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>) => {
      let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
      if (vars) {
        for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
      }
      return text;
    },
    [lang]
  );

  return useMemo(() => <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>, [lang, t, children]);
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
